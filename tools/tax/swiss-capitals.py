"""Refresh the 2026 ESTV estimates for married passive investors in cantonal capitals."""
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / 'cache' / 'tax-ch-estv'
API = ('https://swisstaxcalculator.estv.admin.ch/delegate/ost-integration/v1/'
       'lg-proxy/operation/c3b67379_ESTV/')
CAPITALS = (
    0, 100_000, 200_000, 300_000, *range(400_000, 5_000_001, 200_000),
    *range(5_500_000, 10_000_001, 500_000),
    12_000_000, 15_000_000, 20_000_000, 30_000_000, 50_000_000, 100_000_000,
)
YIELD = 0.015


def post(endpoint, payload):
    body = json.dumps(payload).encode()
    req = Request(API + endpoint, data=body, headers={'Content-Type': 'application/json'})
    with urlopen(req, timeout=25) as response:
        return json.load(response)['response']


def household(capital):
    income = round(capital * YIELD / 2)
    return {
        'SimKey': None, 'TaxYear': 2026, 'Relationship': 2,
        'Confession1': 4, 'Confession2': 4, 'Children': [],
        'Age1': 45, 'Age2': 45, 'RevenueType1': 4, 'RevenueType2': 4,
        'Revenue1': income, 'Revenue2': income, 'Fortune': capital,
    }


def sample(capital):
    path = CACHE / f'{capital}.json'
    if not path.exists():
        rows = post('API_calculateManySimpleTaxes', household(capital) | {'TaxGroupID': 88})
        if len(rows) != 26:
            raise ValueError(f'Expected 26 capitals for CHF {capital}, got {len(rows)}')
        path.write_text(json.dumps(rows))
    return {
        row['Location']['Canton']: row['TotalNetTax']
        for row in json.loads(path.read_text())
    }


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    with ThreadPoolExecutor(max_workers=4) as pool:
        samples = list(pool.map(sample, CAPITALS))
    cantons = sorted(samples[0])
    if any(sorted(values) != cantons for values in samples):
        raise ValueError('ESTV returned inconsistent canton codes')
    output = [
        '// Generated by tools/tax/swiss-capitals.py from the Swiss federal calculator.',
        '// 2026 tax in CHF, married couple age 45, no church, 1.5% taxable fund income.',
        'export const wealthSamples = [' + ', '.join(map(str, CAPITALS)) + '];',
        'export const capitalCommuneTaxes: Record<string, number[]> = {',
    ]
    for canton in cantons:
        output.append(f"  {canton}: [{', '.join(str(values[canton]) for values in samples)}],")
    output.append('};')
    (ROOT / 'src/tax/swiss-capitals.ts').write_text('\n'.join(output) + '\n')


if __name__ == '__main__':
    main()
